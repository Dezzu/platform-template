/**
 * Post-processes the Drizzle schema emitted by the Better Auth CLI.
 *
 * Why this exists: Better Auth's own Kysely migrator maps its `date` fields to
 * `timestamptz` on Postgres (see better-auth/dist/db/get-migration.mjs), but its
 * Drizzle schema generator emits a bare `timestamp(...)`, i.e. `timestamp without
 * time zone`. That is inconsistent, and naive timestamps are a real bug: node-postgres
 * serialises a JS Date with the client's UTC offset, which Postgres then discards for
 * a `timestamp` column. A developer machine on Europe/Rome and a container on UTC
 * therefore store different instants for the same moment.
 *
 * This runs as part of `pnpm auth:generate`, so the fix is reapplied automatically on
 * every Better Auth upgrade. The generated file is still never hand-edited.
 *
 * Remove this script if Better Auth ever makes the Drizzle generator emit timestamptz.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { argv, exit } from 'node:process';

const file = argv[2];
if (!file) {
  console.error('usage: node scripts/postprocess-auth-schema.mjs <path-to-auth.schema.ts>');
  exit(1);
}

const original = readFileSync(file, 'utf8');

// Only bare `timestamp("col")` calls — never touch one that already has options.
const BARE_TIMESTAMP = /timestamp\((["'])([A-Za-z0-9_]+)\1\)/g;
const matches = original.match(BARE_TIMESTAMP) ?? [];

if (matches.length === 0) {
  if (original.includes('withTimezone: true')) {
    console.warn('auth schema: timestamps already timezone-aware, nothing to do');
    exit(0);
  }
  console.error(
    'auth schema: found no timestamp columns at all. The Better Auth CLI output shape ' +
      'has probably changed — review the generated file before trusting this build.',
  );
  exit(1);
}

const patched =
  `// GENERATED by \`pnpm auth:generate\` — do not edit by hand.\n` +
  `// Timestamps are rewritten to timestamptz by scripts/postprocess-auth-schema.mjs;\n` +
  `// see that file for why.\n` +
  original.replace(
    BARE_TIMESTAMP,
    (_m, quote, column) => `timestamp(${quote}${column}${quote}, { withTimezone: true })`,
  );

writeFileSync(file, patched);
console.warn(`auth schema: rewrote ${matches.length} timestamp columns to timestamptz`);
